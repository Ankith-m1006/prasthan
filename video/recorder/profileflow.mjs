// Headless Chrome at 430 px: welcome -> guest -> profile (Tamil Nadu, Madurai, 60+, woman) -> speak usual trip -> links + hints.
import { spawn } from 'node:child_process';
import { writeFileSync } from 'node:fs';
const [url, shotPath] = process.argv.slice(2);
const chrome = spawn('C:/Program Files/Google/Chrome/Application/chrome.exe', ['--headless=new', '--disable-gpu', '--remote-debugging-port=9334', '--user-data-dir=' + process.env.TEMP + '/cdp-prof-profile-' + Date.now(), 'about:blank'], { stdio: 'ignore' });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await sleep(2500);
const tabs = await (await fetch('http://127.0.0.1:9334/json')).json();
const ws = new WebSocket(tabs.find((t) => t.type === 'page').webSocketDebuggerUrl);
await new Promise((r) => ws.addEventListener('open', r));
let n = 0; const pending = new Map(); const errors = [];
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); } if (m.method === 'Runtime.exceptionThrown') errors.push(m.params.exceptionDetails.exception?.description?.slice(0, 300) ?? m.params.exceptionDetails.text); if (m.method === 'Runtime.consoleAPICalled' && m.params.type === 'error') errors.push(JSON.stringify(m.params.args.map((a) => a.value ?? a.description)).slice(0, 300)); if (m.method === 'Log.entryAdded' && m.params.entry.level === 'error') errors.push('LOG ' + m.params.entry.text.slice(0, 200) + ' ' + (m.params.entry.url || '')); });
const send = (method, params = {}) => new Promise((r) => { const id = ++n; pending.set(id, r); ws.send(JSON.stringify({ id, method, params })); });
const ev = async (expression) => (await send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true })).result?.value;
const text = () => ev('document.body.innerText');
const click = (label) => ev(`(() => { const t = ${JSON.stringify(label)}; const el = [...document.querySelectorAll('[role=button],[aria-label]')].find((d) => d.getAttribute('aria-label') === t) || [...document.querySelectorAll('div,span')].filter((d) => d.textContent === t && d.children.length === 0).pop(); if (!el) return false; el.click(); return true; })()`);
const log = (...a) => console.log(...a);
await send('Runtime.enable'); await send('Log.enable');
await send('Emulation.setDeviceMetricsOverride', { width: 430, height: 932, deviceScaleFactor: 2, mobile: true });
await send('Page.navigate', { url });
await sleep(9000);
log('start at', await ev('location.pathname'), '| welcome:', /Continue as guest/.test(await text()));
log('guest click', await click('Continue as guest')); await sleep(2500);
log('profile at', await ev('location.pathname'));
for (const l of ['தமிழ்', 'Tamil Nadu']) { log(l, await click(l)); await sleep(400); }
log('Madurai', await click('Madurai')); await sleep(300);
log('Family', await click('Family')); await sleep(300);
log('60+', await click('60+')); await sleep(300);
log('Woman', await click('Woman')); await sleep(300);
await ev(`(() => { const i = document.querySelector('input[aria-label="Your name"]'); const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; set.call(i, 'Meena'); i.dispatchEvent(new Event('input', { bubbles: true })); return true; })()`);
await sleep(800);
const pt = await text();
log('privacy line:', /Saved only on this phone\. Operators only see totals, never your details\./.test(pt));
const metrics = await send('Page.getLayoutMetrics');
const h = Math.ceil(metrics.cssContentSize?.height ?? 2400);
await send('Emulation.setDeviceMetricsOverride', { width: 430, height: Math.min(h, 4000), deviceScaleFactor: 2, mobile: true });
await sleep(800);
const shot = await send('Page.captureScreenshot', { format: 'png' });
writeFileSync(shotPath, Buffer.from(shot.data, 'base64'));
await send('Emulation.setDeviceMetricsOverride', { width: 430, height: 932, deviceScaleFactor: 2, mobile: true });
log('save', await click('Save and start')); await sleep(4000);
log('speak at', await ev('location.pathname'));
log('saved profile:', await ev(`localStorage.getItem('prasthan.profile.v1')`));
log('usual trip', await click('My usual trip home')); await sleep(1000);
const day = await ev(`(() => { const el = [...document.querySelectorAll('div')].filter((d) => d.textContent === 'Fri 15 Jan' && d.children.length === 0).pop(); if (!el) return false; el.click(); return true; })()`);
log('day', day); await sleep(6000);
const st = await text();
log('trip card Madurai:', /Madurai/.test(st), '| links:', /Book on the official sites/.test(st), '| route page hint:', /opens the route page/.test(st));
log('hints:', st.split('\n').filter((l) => /WHEN YOU BOOK|senior|ladies|women/.test(l)).join(' || '));
log('festival:', st.split('\n').filter((l) => /Pongal|பொங்கல்|Sankranti|flags:/.test(l)).slice(0, 3).join(' || '));
log('errors:', errors.length, errors.slice(0, 5));
ws.close(); chrome.kill();
process.exit(0);
